// Writes src/protocol.ts from the protocol's JSON Schemas in
// packages/wardrik_core/priv/v1. With --check, fails instead where the
// file is not what the schemas make.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { compile, type JSONSchema } from "json-schema-to-typescript";

const schemas = new URL("../../../packages/wardrik_core/priv/v1/", import.meta.url);
const target = new URL("../src/protocol.ts", import.meta.url);
const defsRef = "urn:wardrik:schema:v1:defs#/$defs/";

type Schema = { [key: string]: unknown };

const read = (file: string): Schema =>
  JSON.parse(readFileSync(new URL(file, schemas), "utf8")) as Schema;

const pascal = (text: string): string =>
  text
    .split(/[._]/)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join("");

// Points a reference to a shared definition, or to another resource, at the
// one root's $defs, and drops what only a validator reads.
const local = (node: unknown): unknown => {
  if (Array.isArray(node)) return node.map(local);
  if (node === null || typeof node !== "object") return node;

  // A $ref with keys beside it becomes a type of its own, so the reference
  // alone stands for the one shared type.
  const ref = (node as Schema)["$ref"];
  if (typeof ref === "string" && ref.startsWith(defsRef)) return { $ref: "#/$defs/" + ref.slice(defsRef.length) };
  if (typeof ref === "string" && resourceOf(ref)) return { $ref: "#/$defs/" + resourceOf(ref) };

  const out: Schema = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === "$schema" || key === "$id" || key === "examples") continue;
    out[key] = local(value);
  }
  return out;
};

// What each schema that is not an event's data is called.
const resources: Record<string, string> = {
  "agent.json": "AgentSummary",
  "agent_definition.json": "AgentDefinition",
  "agent_snapshot.json": "AgentSnapshot",
  "authorization.json": "Authorization",
  "cloudevent.json": "Envelope",
  "connecting.json": "Connecting",
  "connections.json": "Connections",
  "decisions.json": "Decisions",
  "definition_read.json": "DefinitionRead",
  "error.json": "ErrorBody",
  "export.json": "ExportPage",
  "nodes.json": "Nodes",
  "server_added.json": "ServerAdded",
  "servers.json": "Servers",
  "token.json": "Token",
  "token_issued.json": "TokenIssued",
  "tokens.json": "Tokens",
  "trigger.json": "Trigger",
  "trigger_definition.json": "TriggerDefinition",
};

// The title of the resource a reference names, where it names one.
const resourceOf = (ref: string): string | undefined =>
  resources[ref.replace(/^urn:wardrik:schema:v1:/, "") + ".json"];

const files = readdirSync(schemas).filter((file) => file.endsWith(".json")).sort();
const events = files.filter((file) => /^[a-z_]+\.[a-z_]+\.json$/.test(file));
const defs = read("defs.json")["$defs"] as Record<string, Schema>;
const $defs: Record<string, unknown> = {};

for (const [name, schema] of Object.entries(defs)) {
  $defs[name] = { ...(local(schema) as Schema), title: name === "error" ? "ErrorInfo" : pascal(name) };
}

for (const [file, title] of Object.entries(resources)) {
  $defs[title] = { ...(local(read(file)) as Schema), title };
}

for (const file of events) {
  const type = file.replace(/\.json$/, "");
  $defs[pascal(type) + "Data"] = { ...(local(read(file)) as Schema), title: pascal(type) + "Data" };
}

const root = { title: "Protocol", type: "object", additionalProperties: false, $defs };

const banner = `// Generated by scripts/generate.ts from packages/wardrik_core/priv/v1. Do not edit.
// Run \`npm run generate\` after changing a schema.`;

const compiled = await compile(root as JSONSchema, "Protocol", {
  bannerComment: banner,
  unreachableDefinitions: true,
  additionalProperties: false,
  format: true,
  style: { printWidth: 100 },
});

const eventMap = events
  .map((file) => {
    const type = file.replace(/\.json$/, "");
    return `  "wardrik.${type}": ${pascal(type)}Data;`;
  })
  .join("\n");

// The generator notes where each definition was referenced from, which says
// nothing to a reader of the types.
const referenced = / \*\n \* This interface was referenced by `Protocol`'s JSON-Schema\n \* via the `definition` "[^"]+"\.\n/g;
const alone = /\/\*\*\n \* This interface was referenced by `Protocol`'s JSON-Schema\n \* via the `definition` "[^"]+"\.\n \*\/\n/g;

const output =
  compiled
    .replace(alone, "")
    .replace(referenced, "")
    .replace(/export interface Protocol \{\}\n\n?/, "") +
  `
/** Each event type, and the data its events carry. */
export interface EventData {
${eventMap}
}

/** An event's type, as its CloudEvent names it. */
export type EventType = keyof EventData;

/** A Wardrik event: a CloudEvent whose data is its type's. */
export type WardrikEvent = {
  [T in EventType]: Omit<Envelope, "type" | "data"> & { type: T; data: EventData[T] };
}[EventType];

/** The event of one type. */
export type EventOf<T extends EventType> = Extract<WardrikEvent, { type: T }>;
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(target, "utf8");
  if (current !== output) {
    console.error("src/protocol.ts is out of date; run `npm run generate`.");
    process.exit(1);
  }
} else {
  writeFileSync(target, output);
}
